"""Pack everything JLCPCB needs into one zip: the Gerber/drill zip, the BOM and CPL in JLC format, and an order
sheet with the board options and the parts that need attention.  The same order sheet is written next to the fab
files as fab/JLCPCB_ORDER.md.  Run after export_fab.py (it calls this itself).

Run:  python scripts/jlc_bundle.py
"""
import os
import zipfile

PRJ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FAB = os.path.join(PRJ, 'fab')
OUT = os.path.join(FAB, 'BEACON_PhoneModule_JLCPCB.zip')
DOC = os.path.join(FAB, 'JLCPCB_ORDER.md')
# source file in fab/ -> name inside the bundle (numbered in upload order)
FILES = {'BEACON_PhoneModule_gerbers.zip': '1_UPLOAD_AS_GERBER_BEACON_PhoneModule_gerbers.zip',
         'BEACON_PhoneModule_BOM_JLC.csv': '2_UPLOAD_AS_BOM_BEACON_PhoneModule_BOM_JLC.csv',
         'BEACON_PhoneModule_CPL_JLC.csv': '3_UPLOAD_AS_CPL_BEACON_PhoneModule_CPL_JLC.csv'}

ORDER = """# BEACON Phone Module: JLCPCB order sheet

## Files to upload

Use the three files below, either from `fab/` in the repository or from `BEACON_PhoneModule_JLCPCB.zip`
(unzip it first; inside it they are numbered 1-3).

**Don't upload `BEACON_PhoneModule_JLCPCB.zip` itself as the Gerber file.** The Gerbers sit in a zip inside
it, and JLC doesn't look inside nested zips, so it reports "0 layers detected".

| Step on jlcpcb.com | File in `fab/` | Name inside the package zip |
|---|---|---|
| 1. Add Gerber file | `BEACON_PhoneModule_gerbers.zip` (upload as is, don't unzip) | `1_UPLOAD_AS_GERBER_...` |
| 2. PCB Assembly: BOM | `BEACON_PhoneModule_BOM_JLC.csv` | `2_UPLOAD_AS_BOM_...` |
| 3. PCB Assembly: CPL | `BEACON_PhoneModule_CPL_JLC.csv` | `3_UPLOAD_AS_CPL_...` |

After step 1, JLC should show **4 layers, 55 x 78.45 mm**.

## PCB options

| Option | Setting |
|---|---|
| Base material | FR-4 |
| Layers | 4 |
| Dimensions | 55 x 78.45 mm (detected from the Gerbers) |
| Thickness | 1.6 mm |
| Impedance control | Yes, stackup **JLC04161H-7628** (the 50 ohm RF CPWG is sized for it) |
| Via covering | **Epoxy filled & capped (via-in-pad, POFV): required**, the nRF52840 has vias in its pads |
| Min via hole / diameter | 0.15 mm / 0.3 mm |
| Surface finish | **ENIG** |
| Outer copper | 1 oz |
| Inner copper | 0.5 oz |
| Mark on PCB | Remove mark, or specify a location, so the order number doesn't land on the silkscreen or logo |
| Everything else | Default |

## Assembly

| Item | What to do |
|---|---|
| Type | Standard PCBA, top side, JLC-added tooling holes |
| J3 (U.FL) | The BOM has no LCSC number: search `U.FL-R-SMT-1(10)` (Hirose) and select it |
| AE1 (patch antenna) | Taoglas WDP.2458.25.4, not stocked at LCSC. Set "do not place" and solder it yourself, or supply it as a consigned part |
| Placement preview | Check pin 1 of every IC against the board marking (U4-U8, filters FL1/FL2, USB-C J1). QFN/SOT rotations are often off by 90 or 180 degrees; rotate them in the viewer if needed |

Then review the DFM report and the price, and place the order.

## Not on the board

The Taoglas FXP70.07.0053A flex antenna (TX) is ordered separately. It plugs into J3 at final assembly.

---
Generated by `scripts/jlc_bundle.py`; edit the text there, not here.
"""

missing = [f for f in FILES if not os.path.exists(os.path.join(FAB, f))]
if missing:
    raise SystemExit('run export_fab.py first, missing: ' + ', '.join(missing))
with open(DOC, 'w', encoding='utf8', newline='\n') as f:
    f.write(ORDER)
with zipfile.ZipFile(OUT, 'w', zipfile.ZIP_DEFLATED) as z:
    z.writestr('0_READ_ME_FIRST_JLCPCB_ORDER.txt', ORDER.replace('\n', '\r\n'))
    for src, name in FILES.items():
        z.write(os.path.join(FAB, src), name)
print('JLCPCB bundle:', OUT)
print('order sheet:', DOC)
